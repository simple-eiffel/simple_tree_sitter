/*
 * embed_queries: turn the query files into sts_queries.c.
 *
 *   embed_queries <queries directory> <language> ...  >  sts_queries.c
 *
 * For each language it reads highlights.scm, folds.scm and brackets.scm from
 * <queries directory>/<language>/, and writes them as byte arrays (not string
 * literals, which some compilers limit in length). A file that is missing gives
 * no query of that kind. Line ends are written as "\n" whatever the file has.
 */

#include <stdio.h>
#include <string.h>

static const char *const kinds[] = { "highlights", "folds", "brackets" };

static int emit(const char *a_directory, const char *a_language, int a_kind)
	/* Write the array for one query file; 1 when the file exists. */
{
	char l_path[1024];
	FILE *l_file;
	int c, n = 0;
	if (strlen(a_directory) + strlen(a_language) + 32 > sizeof(l_path)) {
		return 0;
	}
	sprintf(l_path, "%s/%s/%s.scm", a_directory, a_language, kinds[a_kind]);
	l_file = fopen(l_path, "rb");
	if (!l_file) {
		return 0;
	}
	printf("static const char q_%s_%s[] = {", a_language, kinds[a_kind]);
	while ((c = fgetc(l_file)) != EOF) {
		if (c == '\r') {
			continue;
		}
		printf("%s%d,", (n % 24 == 0) ? "\n\t" : "", c);
		n++;
	}
	printf("%s0\n};\n\n", (n % 24 == 0) ? "\n\t" : "");
	fclose(l_file);
	return 1;
}

int main(int argc, char **argv)
{
	int l_has[64][3];
	int i, k;
	if (argc < 3 || argc > 66) {
		fprintf(stderr, "usage: embed_queries <queries directory> <language> ...\n");
		return 2;
	}
	printf("/*\n * Generated by tools/embed_queries.c from the files in queries/. Do not edit:\n");
	printf(" * change the query file and run `make queries' (or build.bat queries).\n */\n\n");
	printf("#include <string.h>\n\n");
	for (i = 2; i < argc; i++) {
		for (k = 0; k < 3; k++) {
			l_has[i - 2][k] = emit(argv[1], argv[i], k);
		}
	}
	printf("const char *sts_bundled_query(const char *a_language, int a_kind)\n");
	printf("\t/* The query of `a_kind' (0 highlights, 1 folds, 2 brackets) for `a_language'; NULL when none. */\n{\n");
	for (i = 2; i < argc; i++) {
		printf("\tif (strcmp(a_language, \"%s\") == 0) {\n", argv[i]);
		for (k = 0; k < 3; k++) {
			if (l_has[i - 2][k]) {
				printf("\t\tif (a_kind == %d) {\n\t\t\treturn q_%s_%s;\n\t\t}\n", k, argv[i], kinds[k]);
			}
		}
		printf("\t}\n");
	}
	printf("\treturn NULL;\n}\n");
	return 0;
}
